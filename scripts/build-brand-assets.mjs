import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const geometry=JSON.parse(await readFile(path.join(root,'brand/relais.geometry.json'),'utf8'));
const dir=path.join(root,'public/brand');await mkdir(dir,{recursive:true});
const blue='#4b93ff',ink='#181819',wordScale=.84,wordX=148,wordY=22;
const width=Number((wordX+geometry.wordmark.ratio*100*wordScale).toFixed(3));
const paths=items=>items.map(d=>`<path d="${d}" fill-rule="evenodd"/>`).join('');
const svg=(viewBox,body,title)=>`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${title}">${body}</svg>\n`;
const symbol=color=>`<g fill="${color}">${paths(geometry.symbol.paths)}</g>`;
const lockup=(mark,text)=>svg(`0 0 ${width} 128`,symbol(mark)+`<g fill="${text}" transform="translate(${wordX} ${wordY}) scale(${wordScale})">${paths(geometry.wordmark.paths)}</g>`,'Braand - Relais');
const outputs={
 'relais-symbol.svg':svg('0 0 128 128',symbol(blue),'Braand - symbole Relais'),
 'relais-symbol-black.svg':svg('0 0 128 128',symbol(ink),'Braand - symbole Relais noir'),
 'relais-symbol-white.svg':svg('0 0 128 128',symbol('#ffffff'),'Braand - symbole Relais blanc'),
 'relais-logo.svg':lockup(blue,ink),
 'relais-logo-dark.svg':lockup(blue,'#ffffff'),
 'relais-logo-black.svg':lockup(ink,ink),
 'relais-logo-white.svg':lockup('#ffffff','#ffffff'),
 'relais-app-icon.svg':svg('0 0 128 128',`<rect width="128" height="128" rx="30" fill="${blue}"/><g transform="translate(12 12) scale(.8125)">${symbol('#ffffff')}</g>`,'Braand'),
};
for(const [name,content]of Object.entries(outputs))await writeFile(path.join(dir,name),content);
await writeFile(path.join(root,'public/favicon.svg'),svg('0 0 128 128',`<rect width="128" height="128" rx="28" fill="${ink}"/>${symbol(blue)}`,'Braand'));
const constants={name:'Braand',identity:'Relais',version:'1.0.0',blue,ink,symbolViewBox:geometry.symbol.viewBox,symbolPaths:geometry.symbol.paths,wordmarkPaths:geometry.wordmark.paths,wordmarkRatio:geometry.wordmark.ratio,lockupViewBox:`0 0 ${width} 128`,lockupRatio:width/128,wordX,wordY,wordScale};
await writeFile(path.join(root,'lib/brand.mjs'),'// Generated by scripts/build-brand-assets.mjs from brand/relais.geometry.json.\nexport const BRAAND_BRAND='+JSON.stringify(constants)+';\n');
await writeFile(path.join(dir,'manifest.json'),JSON.stringify({name:'Braand',identity:'Relais',version:'1.0.0',updated:'2026-10-30',primary:blue,files:Object.keys(outputs),source:'brand/relais.geometry.json'},null,2)+'\n');
console.log(JSON.stringify({identity:'Relais',svgFiles:Object.keys(outputs).length+1,lockupRatio:constants.lockupRatio}));
